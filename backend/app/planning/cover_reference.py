"""Cover-crop agronomic reference (INRAE means of European trials).

Data: ``data/cover_crop_reference.yaml`` (generated by ``scripts/build_cover_crop_reference.py``).
Selection never crosses seasons or species: the requested season, else the season-less row,
else ``no_data``.
"""
from __future__ import annotations

import os
from functools import cache
from pathlib import Path
from typing import Any

import yaml

SOURCE_ID = "thiebeau_inrae_2021"
COVERAGE = "europe_mostly_north_central"

Row = dict[str, Any]
ReferenceData = dict[str, dict[str, Row]]


@cache
def load_reference_data() -> ReferenceData:
    """``{species_slug: {season: row}}`` from the data file; empty when the file is absent."""
    path = Path(os.getenv("DATA_DIR", "./data")) / "cover_crop_reference.yaml"
    if not path.exists():
        return {}
    with path.open("r", encoding="utf-8") as fh:
        return (yaml.safe_load(fh) or {}).get("species") or {}


def select_row(rows: dict[str, Row], season: str) -> tuple[str | None, Row | None]:
    """The row of the requested season, else the ``unspecified`` one, else nothing."""
    for key in (season, "unspecified"):
        if key in rows:
            return key, rows[key]
    return None, None


def n_accumulated(row: Row) -> int | None:
    """Nitrogen in the aerial biomass (kg N/ha) = dry matter x %N; None unless both means exist."""
    dm, n_pct = row.get("dm_t_ha"), row.get("n_pct")
    if not dm or not n_pct or dm.get("mean") is None or n_pct.get("mean") is None:
        return None
    return round(dm["mean"] * 1000 * n_pct["mean"] / 100)


def reference_for(species: str, season: str, data: ReferenceData) -> dict[str, Any]:
    """Response body (without attributions) for a canonical species slug and a season."""
    used, row = select_row(data.get(species) or {}, season)
    base = {"species": species, "season_requested": season, "coverage": COVERAGE}
    if row is None:
        return {**base, "season_used": None, "status": "no_data", "aerial": None}
    aerial = {"dm_t_ha": row.get("dm_t_ha"), "n_pct": row.get("n_pct"), "c_n": row.get("c_n"),
              "n_accumulated_kg_ha": n_accumulated(row)}
    return {**base, "season_used": used, "status": "ok", "aerial": aerial}
